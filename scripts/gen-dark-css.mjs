// Generates dark-mode.css from the app's stylesheets: every colour declaration is
// re-emitted under html[data-theme=dark] with light surfaces darkened and dark text
// lightened (hue kept). Images are never filtered. Run: node scripts/gen-dark-css.mjs
import fs from 'node:fs';
const FILES = ['styles.css', 'genesis.css', 'psalm-walk.css', 'psalm-art.css', 'psalms-book.css', 'psalm-verse-study.css'];
const vars = {};
const hex = h => { h = h.slice(1); if (h.length <= 4) h = [...h.slice(0, 3)].map(c => c + c).join('') + (h[3] ? h[3] + h[3] : ''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)).concat(h.length === 8 ? [parseInt(h.slice(6, 8), 16)] : []); };
const toHsl = ([r, g, b]) => { r /= 255; g /= 255; b /= 255; const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2; let h = 0, s = 0; if (mx !== mn) { const d = mx - mn; s = l > .5 ? d / (2 - mx - mn) : d / (mx + mn); h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; h /= 6; } return [h, s, l]; };
const fromHsl = ([h, s, l]) => { const f = n => { const k = (n + h * 12) % 12, a = s * Math.min(l, 1 - l); return Math.round(255 * (l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)))); }; return [f(0), f(8), f(4)]; };
const out = (rgb, a) => '#' + rgb.map(v => v.toString(16).padStart(2, '0')).join('') + (a !== undefined ? a.toString(16).padStart(2, '0') : '');
const lum = ([r, g, b]) => (0.3 * r + 0.59 * g + 0.11 * b) / 255;
function parse(c) { if (c === 'white' || c === '#fff' || c === '#ffffff') return [255, 255, 255]; if (/^#[0-9a-f]{3,8}$/i.test(c)) return hex(c); return null; }
function mapBg(c) { const v = parse(c); if (!v || lum(v) < .6) return null; const [h, s, l] = toHsl(v); const nl = .09 + (1 - l) * .9; return out(fromHsl([h, Math.min(s, .15), Math.min(nl, .26)]), v[3]); }
function mapText(c) { const v = parse(c); if (!v || lum(v) > .55) return null; const [h, s, l] = toHsl(v); return out(fromHsl([h, Math.min(s, .35), Math.min(.93, .72 + (.5 - Math.min(l, .5)) * .45)]), v[3]); }
function mapBorder(c) { const v = parse(c); if (!v || lum(v) < .6) return null; const [h, s] = toHsl(v); return out(fromHsl([h, Math.min(s, .2), .3]), v[3]); }
const rules = [];
for (const f of FILES) {
  let css = fs.readFileSync(f, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of css.matchAll(/--([\w-]+):\s*([^;}]+)/g)) vars[m[1]] = m[2].trim();
}
function walk(css, wrap) {
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i); if (open < 0) break;
    const sel = css.slice(i, open).trim();
    if (sel.startsWith('@media') || sel.startsWith('@supports')) {
      let depth = 1, j = open + 1; while (depth && j < css.length) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
      walk(css.slice(open + 1, j - 1), sel); i = j; continue;
    }
    const close = css.indexOf('}', open); const body = css.slice(open + 1, close); i = close + 1;
    if (sel === 'body' || /art-credit|art-caption|scene-label/.test(sel) || sel.startsWith('@') || /^(from|to|\d+%)/.test(sel)) continue;
    const decls = [];
    for (const d of body.split(';')) {
      const k = d.indexOf(':'); if (k < 0) continue;
      const prop = d.slice(0, k).trim(); let val = d.slice(k + 1).trim(); const imp = /!important/.test(val); val = val.replace(/!important/, '').trim();
      let resolved = val.replace(/var\(--([\w-]+)\)/g, (_, n) => vars[n] || _);
      let nv = null;
      if (prop === 'background' || prop === 'background-color') { if (/^(#[0-9a-f]{3,8}|white)$/i.test(resolved)) nv = mapBg(resolved); }
      else if (prop === 'color' || prop === 'fill' && false) nv = mapText(resolved);
      else if (/^border(-top|-bottom|-left|-right)?(-color)?$/.test(prop)) { const c = resolved.match(/#[0-9a-f]{3,8}\b/i); if (c) { const m = mapBorder(c[0]); if (m) nv = resolved.replace(c[0], m); } }
      if (nv) decls.push(`${prop}:${nv}${imp ? '!important' : ''}`);
    }
    if (!decls.length) continue;
    const scoped = sel.split(',').map(s => { s = s.trim(); if (s === ':root' || s === 'html') return 'html[data-theme=dark]'; return 'html[data-theme=dark] ' + s.replace(/^(html|:root)\s+/, ''); }).join(',');
    rules.push((wrap ? wrap + '{' : '') + scoped + '{' + decls.join(';') + '}' + (wrap ? '}' : ''));
  }
}
for (const f of FILES) walk(fs.readFileSync(f, 'utf8').replace(/\/\*[\s\S]*?\*\//g, ''), '');
const base = `html[data-theme=dark]{color-scheme:dark;--paper:#141a17;--cream:#1d2420;--ink:#e6e3d6;--muted:#a9b2a6;--line:#34403a}
html[data-theme=dark] body{background:#141a17;color:#e6e3d6}
html[data-theme=dark] a[href^="#/people/"][style]{color:#dcb67a!important}
html[data-theme=dark] input,html[data-theme=dark] select,html[data-theme=dark] textarea{color:#e6e3d6}
html[data-theme=dark] img{filter:none}
`;
fs.writeFileSync('dark-mode.css', '/* Generated by scripts/gen-dark-css.mjs — do not edit by hand. */\n' + base + rules.join('\n') + '\n');
console.log('dark-mode.css rules:', rules.length);
