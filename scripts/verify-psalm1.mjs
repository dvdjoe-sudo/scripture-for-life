import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const values=new Map([['scripture-for-life.notes','existing notes'],['scripture-for-life.psalm23-place','5']]);
const ctx={window:{SFL_PSALMS:{switcher:()=>'<nav></nav>'}},document:{addEventListener(){}},localStorage:{getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)},location:{hash:'#/study/1/1'}};
for(const file of ['psalm-verse-study.js','psalm1.js'])vm.runInNewContext(fs.readFileSync(file,'utf8'),ctx);
const study=ctx.window.SFL_VERSE_STUDIES,config=study.studies[1],bible=JSON.parse(fs.readFileSync('data/bible.json','utf8')).books,chapter=Object.fromEntries(bible[18].chapters[0]);
const escapeHTML=v=>String(v).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const tools={chapter,escapeHTML,refURL:r=>'#/read/19/1',icon:()=>'',saveButton:r=>`<button data-ref="${r}">Save</button>`,noteField:()=>'<textarea></textarea>',hydrateNotes(){}};
assert.equal(config.verses.length,6);
assert.equal(new Set(config.verses.map(v=>v.meaning)).size,6);
assert.equal(new Set(config.verses.map(v=>v.context)).size,6);
assert.equal(new Set(config.verses.map(v=>v.art)).size,6);
const checkRef=ref=>{const m=/^(.+?) (\d+):(\d+)$/.exec(ref);assert(m);assert(bible.find(b=>b.name===m[1])?.chapters[+m[2]-1]?.some(([v])=>v===+m[3]),ref+' exists in BSB');};
for(let n=1;n<=6;n++){
 const row=config.verses[n-1],html=study.render(1,n,tools);
 assert(html.includes(`data-speakref="Psalm 1:${n}">${escapeHTML(chapter[n])}</p>`),'Exact Scripture for verse '+n);
 assert.equal((html.match(/data-verse-study-art=/g)||[]).length,1);
 assert.equal((html.match(/role="tab"/g)||[]).length,4);
 assert.equal((html.match(/>Verse \d<\/a>/g)||[]).length,6,'Every verse is freely accessible');
 assert(!html.includes('href="#/study/1/0"')&&!html.includes('href="#/study/1/7"'));
 assert.equal(study.progress(1),n);assert.equal(study.link('Psalm 1:'+n),'#/study/1/'+n);
 assert(row.meaning.length>300&&row.context.length>180&&row.explore.length>=2&&row.reflect.length>50);
 row.related.forEach(checkRef);
 const image=fs.readFileSync(row.art);assert.equal(image.subarray(8,12).toString(),'WEBP');
 assert(image.equals(fs.readFileSync('www/'+row.art)),'Matching Android artwork');
 assert(fs.readFileSync('sw.js','utf8').includes(row.art),'Artwork cached offline');
}
config.people.forEach(p=>checkRef(p.ref));
assert.equal(values.get('scripture-for-life.notes'),'existing notes');
assert.equal(values.get('scripture-for-life.psalm23-place'),'5');
assert.equal(study.link('Psalm 1:7'),'');assert.equal(study.link('Psalm 2:1'),'');
assert.throws(()=>study.render(1,0,tools));assert.throws(()=>study.render(1,7,tools));
assert.throws(()=>study.render(2,1,tools));
values.set('scripture-for-life.psalm1-place','wrong');assert.equal(study.progress(1),1);
ctx.localStorage.getItem=()=>{throw Error('blocked');};ctx.localStorage.setItem=()=>{throw Error('blocked');};
assert.equal(study.progress(1),1);assert.doesNotThrow(()=>study.render(1,2,tools));
for(const f of ['psalm1.js','psalm-verse-study.js','psalm-verse-study.css'])assert.equal(fs.readFileSync(f,'utf8'),fs.readFileSync('www/'+f,'utf8'));
console.log('PASS — Psalm 1: all six exact verses, distinct paintings and verse notes, references, open navigation, isolated resume, blocked storage, and matching offline/Android assets.');
