#!/usr/bin/env node
/* Generate people-cards.js: the card registry for the lazily loaded People profiles.
   The FILES list below is FROZEN in today's index.html tag order (2026-11-15); it is the
   durable record of the profile order now that index.html no longer carries the tags.
   A new people file is appended to FILES, never inserted, and this script is re-run.
   Usage: node scripts/gen-people-cards.mjs [--check] */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['exodus-people.js', 'judges-people.js', 'genesis-people.js', 'joshua-people.js', 'ruth-people.js', 'samuel1-people.js', 'samuel2-people.js', 'kings1-people.js', 'kings2-people.js', 'jonah-people.js', 'amos-people.js', 'hosea-people.js', 'isaiah-people.js', 'micah-people.js', 'nahum-people.js', 'zephaniah-people.js', 'jeremiah-people.js', 'habakkuk-people.js', 'obadiah-people.js', 'ezekiel-people.js', 'daniel-people.js', 'haggai-people.js', 'zechariah-people.js', 'joel-people.js', 'malachi-people.js', 'chronicles-people.js', 'ezra-people.js', 'esther-people.js', 'nehemiah-people.js', 'job-people.js', 'matthew-people.js', 'luke-people.js', 'john-people.js', 'acts-people.js', 'corinthians1-people.js', 'corinthians2-people.js', 'romans-people.js', 'ephesians-people.js', 'philippians-people.js', 'colossians-people.js', 'philemon-people.js', 'hebrews-people.js', 'peter2-people.js', 'john1-people.js', 'john3-people.js', 'jude-people.js', 'timothy2-people.js', 'revelation-people.js', 'audit-people.js', 'leviticus-people.js', 'numbers-people.js'];

function build() {
  const onDisk = fs.readdirSync(root).filter(f => f.endsWith('-people.js')).sort();
  const frozen = [...FILES].sort();
  if (JSON.stringify(onDisk) !== JSON.stringify(frozen)) {
    throw new Error('people file set mismatch. On disk: ' + onDisk.join(', ') + ' | FILES: ' + frozen.join(', '));
  }
  const win = {};
  const ctx = vm.createContext({ window: win, console });
  const run = f => vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx, { filename: f });
  run('content.js');
  const baseIds = new Set((win.PEOPLE || []).map(p => p.id));
  const owner = {};
  for (const f of FILES) {
    const before = (win.PEOPLE || []).length;
    run(f);
    for (const p of (win.PEOPLE || []).slice(before)) {
      if (owner[p.id]) throw new Error('profile ' + p.id + ' defined by both ' + owner[p.id] + ' and ' + f);
      if (baseIds.has(p.id)) throw new Error('profile ' + p.id + ' defined by both content.js and ' + f);
      owner[p.id] = f;
    }
  }
  const cards = (win.PEOPLE || []).filter(p => owner[p.id]).map(p => ({ id: p.id, name: p.name, icon: p.icon, tag: p.tag, topic: p.relatedTopic, file: owner[p.id] }));
  if (!cards.length) throw new Error('no cards generated');
  const body = cards.map(c => JSON.stringify(c)).join(',\n');
  return '/* Generated by scripts/gen-people-cards.mjs from the *-people.js files. Do not edit by hand. */\nwindow.PEOPLE_CARDS = [\n' + body + '\n];\n';
}

const out = build();
const target = path.join(root, 'people-cards.js');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) { console.error('people-cards.js is stale. Run: node scripts/gen-people-cards.mjs'); process.exit(1); }
  console.log('people-cards.js is current (' + JSON.parse(out.slice(out.indexOf('['), out.lastIndexOf(']') + 1)).length + ' cards).');
} else {
  fs.writeFileSync(target, out);
  console.log('wrote people-cards.js');
}
